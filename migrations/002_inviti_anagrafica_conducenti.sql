-- Migrazione additiva. Backup/staging prima dell'applicazione.
BEGIN;
CREATE TABLE IF NOT EXISTS public.inviti_anagrafica_conducenti (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 anagrafica_id BIGINT NOT NULL REFERENCES public.anagrafica_conducenti(id),
 operatore_id INTEGER NOT NULL REFERENCES public.utente(id),
 token_hash CHAR(64) NOT NULL UNIQUE,
 email_destinatario TEXT NOT NULL,
 scade_il TIMESTAMPTZ NOT NULL,
 consumato_il TIMESTAMPTZ,
 revocato_il TIMESTAMPTZ,
 creato_il TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 CONSTRAINT inviti_anagrafica_scadenza CHECK (scade_il > creato_il)
);
CREATE INDEX IF NOT EXISTS inviti_anagrafica_lookup_idx ON public.inviti_anagrafica_conducenti(anagrafica_id,creato_il DESC);
CREATE UNIQUE INDEX IF NOT EXISTS inviti_anagrafica_unico_pendente_idx
 ON public.inviti_anagrafica_conducenti(anagrafica_id)
 WHERE consumato_il IS NULL AND revocato_il IS NULL;
COMMIT;
