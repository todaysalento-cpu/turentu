-- TURENTU / POPBUS V2 - MIGRAZIONE 001 (UP)
-- Tabella per riserve temporanee su corse POPBUS gia' confermate.
-- NON applicare in produzione prima del collaudo end-to-end.
-- Eseguire con psql -v ON_ERROR_STOP=1 -f <file.sql> dopo aver copiato il TXT in .sql.
-- Nessuna modifica a pending, prenotazioni, corse o flussi NCC.

BEGIN;

CREATE TABLE IF NOT EXISTS public.popbus_riserve (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id UUID NOT NULL,
    corsa_id INTEGER NOT NULL REFERENCES public.corse(id) ON DELETE RESTRICT,
    cliente_id INTEGER NOT NULL REFERENCES public.utente(id) ON DELETE RESTRICT,
    posti_richiesti INTEGER NOT NULL CHECK (posti_richiesti > 0),
    start_offset NUMERIC NOT NULL CHECK (start_offset >= 0),
    end_offset NUMERIC NOT NULL,
    start_index_polyline INTEGER NOT NULL CHECK (start_index_polyline >= 0),
    end_index_polyline INTEGER NOT NULL,
    prezzo NUMERIC(12,2) NOT NULL CHECK (prezzo >= 0.50),
    currency VARCHAR(3) NOT NULL DEFAULT 'eur' CHECK (currency = 'eur'),
    payment_intent_id VARCHAR(255),
    stato VARCHAR(20) NOT NULL DEFAULT 'riservata'
        CHECK (stato IN ('riservata', 'confermata', 'scaduta', 'annullata')),
    expires_at TIMESTAMPTZ NOT NULL,
    prenotazione_id INTEGER UNIQUE REFERENCES public.prenotazioni(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT popbus_riserve_offsets_chk CHECK (end_offset > start_offset),
    CONSTRAINT popbus_riserve_indices_chk CHECK (end_index_polyline > start_index_polyline),
    CONSTRAINT popbus_riserve_confirmed_chk CHECK (
        (stato = 'confermata' AND prenotazione_id IS NOT NULL)
        OR (stato <> 'confermata' AND prenotazione_id IS NULL)
    ),
    CONSTRAINT popbus_riserve_expiry_chk CHECK (expires_at > created_at),
    CONSTRAINT popbus_riserve_request_uk UNIQUE (request_id)
);

-- Una autorizzazione Stripe non puo' finanziare due riserve diverse.
CREATE UNIQUE INDEX IF NOT EXISTS popbus_riserve_payment_intent_uk
    ON public.popbus_riserve(payment_intent_id)
    WHERE payment_intent_id IS NOT NULL;

-- Per calcolo occupazione: includere solo stato riservata con expires_at > NOW().
-- NOW() non va in un indice parziale: la condizione temporale si applica in query.
CREATE INDEX IF NOT EXISTS popbus_riserve_active_corsa_idx
    ON public.popbus_riserve(corsa_id, expires_at, start_offset, end_offset)
    WHERE stato = 'riservata';

CREATE INDEX IF NOT EXISTS popbus_riserve_cliente_idx
    ON public.popbus_riserve(cliente_id, created_at DESC);

COMMIT;

