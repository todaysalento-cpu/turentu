-- Nessuna modifica a PIXEL, POPBUS V2, worker, corse o pagamenti.

BEGIN;

-- 1. Procacciatori commerciali
CREATE TABLE IF NOT EXISTS public.procaccio_procacciatori (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome TEXT NOT NULL,
  cognome TEXT NOT NULL,
  email TEXT,
  telefono TEXT,
  territorio TEXT,
  attivo BOOLEAN NOT NULL DEFAULT TRUE,
  note TEXT,
  creato_il TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  aggiornato_il TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT procaccio_procacciatori_nome_ck
    CHECK (length(btrim(nome)) > 0),
  CONSTRAINT procaccio_procacciatori_cognome_ck
    CHECK (length(btrim(cognome)) > 0)
);

-- 2. Operatori NCC potenziali
CREATE TABLE IF NOT EXISTS public.procaccio_operatori (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ragione_sociale TEXT NOT NULL,
  partita_iva TEXT,
  comune TEXT,
  provincia TEXT,
  regione TEXT,
  indirizzo TEXT,
  telefono TEXT,
  email TEXT,
  sito_web TEXT,
  stato TEXT NOT NULL DEFAULT 'da_contattare',
  fonte TEXT,
  procacciatore_id BIGINT REFERENCES
    public.procaccio_procacciatori(id) ON DELETE SET NULL,
  prossimo_contatto_il TIMESTAMPTZ,
  note TEXT,
  archiviato_il TIMESTAMPTZ,
  creato_il TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  aggiornato_il TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT procaccio_operatori_nome_ck
    CHECK (length(btrim(ragione_sociale)) > 0),
  CONSTRAINT procaccio_operatori_stato_ck
    CHECK (stato IN (
      'da_contattare',
      'contattato',
      'interessato',
      'in_trattativa',
      'aderito',
      'non_interessato',
      'non_raggiungibile'
    )),
  CONSTRAINT procaccio_operatori_piva_ck
    CHECK (
      partita_iva IS NULL OR
      partita_iva ~ '^[0-9]{11}$'
    )
);

-- 3. Flotta dichiarata per tipologia
CREATE TABLE IF NOT EXISTS public.procaccio_flotte (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  operatore_id BIGINT NOT NULL REFERENCES
    public.procaccio_operatori(id) ON DELETE CASCADE,
  tipologia TEXT NOT NULL,
  quantita INTEGER NOT NULL DEFAULT 0,
  note TEXT,
  aggiornato_il TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT procaccio_flotte_quantita_ck
    CHECK (quantita >= 0),
  CONSTRAINT procaccio_flotte_tipologia_ck
    CHECK (length(btrim(tipologia)) > 0),
  CONSTRAINT procaccio_flotte_unica
    UNIQUE (operatore_id, tipologia)
);

-- 4. Referenti commerciali
CREATE TABLE IF NOT EXISTS public.procaccio_contatti (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  operatore_id BIGINT NOT NULL REFERENCES
    public.procaccio_operatori(id) ON DELETE CASCADE,
  nome TEXT NOT NULL,
  cognome TEXT,
  ruolo TEXT,
  telefono TEXT,
  email TEXT,
  principale BOOLEAN NOT NULL DEFAULT FALSE,
  note TEXT,
  creato_il TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT procaccio_contatti_nome_ck
    CHECK (length(btrim(nome)) > 0)
);

-- 5. Attività commerciali
CREATE TABLE IF NOT EXISTS public.procaccio_attivita (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  operatore_id BIGINT NOT NULL REFERENCES
    public.procaccio_operatori(id) ON DELETE CASCADE,
  procacciatore_id BIGINT REFERENCES
    public.procaccio_procacciatori(id) ON DELETE SET NULL,
  tipo TEXT NOT NULL,
  stato TEXT NOT NULL DEFAULT 'programmata',
  titolo TEXT NOT NULL,
  descrizione TEXT,
  programmata_il TIMESTAMPTZ,
  completata_il TIMESTAMPTZ,
  esito TEXT,
  creato_il TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  aggiornato_il TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT procaccio_attivita_tipo_ck
    CHECK (tipo IN (
      'telefonata',
      'email',
      'visita',
      'appuntamento',
      'messaggio',
      'altro'
    )),
  CONSTRAINT procaccio_attivita_stato_ck
    CHECK (stato IN (
      'programmata',
      'completata',
      'annullata'
    )),
  CONSTRAINT procaccio_attivita_titolo_ck
    CHECK (length(btrim(titolo)) > 0)
);

-- 6. Storico delle modifiche
CREATE TABLE IF NOT EXISTS public.procaccio_storico (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  operatore_id BIGINT NOT NULL REFERENCES
    public.procaccio_operatori(id) ON DELETE CASCADE,
  azione TEXT NOT NULL,
  campo TEXT,
  valore_precedente TEXT,
  valore_nuovo TEXT,
  dettagli JSONB,
  autore_tipo TEXT NOT NULL DEFAULT 'admin',
  autore_id BIGINT,
  creato_il TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT procaccio_storico_azione_ck
    CHECK (length(btrim(azione)) > 0)
);

-- Indici per ricerca e dashboard
CREATE UNIQUE INDEX IF NOT EXISTS
  procaccio_operatori_piva_unica_idx
  ON public.procaccio_operatori (partita_iva)
  WHERE partita_iva IS NOT NULL AND archiviato_il IS NULL;

CREATE INDEX IF NOT EXISTS
  procaccio_operatori_stato_idx
  ON public.procaccio_operatori (stato);

CREATE INDEX IF NOT EXISTS
  procaccio_operatori_territorio_idx
  ON public.procaccio_operatori (provincia, comune);

CREATE INDEX IF NOT EXISTS
  procaccio_operatori_procacciatore_idx
  ON public.procaccio_operatori (procacciatore_id);

CREATE INDEX IF NOT EXISTS
  procaccio_operatori_prossimo_contatto_idx
  ON public.procaccio_operatori (prossimo_contatto_il);

CREATE INDEX IF NOT EXISTS
  procaccio_contatti_operatore_idx
  ON public.procaccio_contatti (operatore_id);

CREATE UNIQUE INDEX IF NOT EXISTS
  procaccio_contatti_principale_idx
  ON public.procaccio_contatti (operatore_id)
  WHERE principale = TRUE;

CREATE INDEX IF NOT EXISTS
  procaccio_attivita_operatore_idx
  ON public.procaccio_attivita (operatore_id);

CREATE INDEX IF NOT EXISTS
  procaccio_attivita_scadenza_idx
  ON public.procaccio_attivita (programmata_il)
  WHERE stato = 'programmata';

CREATE INDEX IF NOT EXISTS
  procaccio_storico_operatore_idx
  ON public.procaccio_storico (operatore_id, creato_il DESC);

COMMIT;
