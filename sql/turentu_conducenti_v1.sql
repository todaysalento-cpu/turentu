-- Eseguire prima in staging. Nessuna modifica ai worker PIXEL/POPBUS.
BEGIN;
CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE IF NOT EXISTS conducenti_operatori (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  operatore_id integer NOT NULL REFERENCES utente(id),
  conducente_id integer NOT NULL REFERENCES utente(id),
  stato text NOT NULL DEFAULT 'attivo' CHECK (stato IN ('invitato','attivo','sospeso')),
  assegnabile_automaticamente boolean NOT NULL DEFAULT false,
  creato_il timestamptz NOT NULL DEFAULT now(),
  aggiornato_il timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT conducenti_operatori_unici UNIQUE (operatore_id, conducente_id)
);
CREATE INDEX IF NOT EXISTS idx_conducenti_operatori_conducente ON conducenti_operatori(conducente_id);

CREATE TABLE IF NOT EXISTS impostazioni_assegnazione_operatori (
  operatore_id integer PRIMARY KEY REFERENCES utente(id),
  modalita text NOT NULL DEFAULT 'manuale' CHECK (modalita IN ('manuale','automatica')),
  aggiornato_il timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS turni_conducenti (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rapporto_id bigint NOT NULL REFERENCES conducenti_operatori(id) ON DELETE CASCADE,
  giorno_settimana smallint NOT NULL CHECK (giorno_settimana BETWEEN 1 AND 7),
  ora_inizio time NOT NULL,
  ora_fine time NOT NULL,
  fuso_orario text NOT NULL DEFAULT 'Europe/Rome',
  attivo boolean NOT NULL DEFAULT true,
  CONSTRAINT turni_conducenti_ore_valide CHECK (ora_fine > ora_inizio)
);
CREATE INDEX IF NOT EXISTS idx_turni_conducenti_rapporto ON turni_conducenti(rapporto_id, giorno_settimana);

CREATE TABLE IF NOT EXISTS eccezioni_turni_conducenti (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rapporto_id bigint NOT NULL REFERENCES conducenti_operatori(id) ON DELETE CASCADE,
  intervallo tstzrange NOT NULL,
  tipo text NOT NULL CHECK (tipo IN ('disponibile','indisponibile')),
  nota text,
  CONSTRAINT eccezioni_turni_intervallo_valido CHECK (NOT isempty(intervallo) AND lower_inc(intervallo) AND NOT upper_inc(intervallo) AND NOT lower_inf(intervallo) AND NOT upper_inf(intervallo))
);
CREATE INDEX IF NOT EXISTS idx_eccezioni_turni_rapporto ON eccezioni_turni_conducenti(rapporto_id);

CREATE TABLE IF NOT EXISTS assegnazioni_conducenti (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  operatore_id integer NOT NULL REFERENCES utente(id),
  conducente_id integer NOT NULL REFERENCES utente(id),
  veicolo_id integer NOT NULL REFERENCES veicolo(id),
  corsa_id integer REFERENCES corse(id),
  attivazione_id bigint REFERENCES popbus_attivazioni(id),
  intervallo_operativo tstzrange NOT NULL,
  modalita text NOT NULL CHECK (modalita IN ('automatica','manuale','titolare')),
  stato text NOT NULL DEFAULT 'assegnata' CHECK (stato IN ('assegnata','annullata','completata')),
  creata_il timestamptz NOT NULL DEFAULT now(),
  aggiornata_il timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT assegnazioni_conducenti_target CHECK ((corsa_id IS NOT NULL) <> (attivazione_id IS NOT NULL)),
  CONSTRAINT assegnazioni_conducenti_intervallo_valido CHECK (NOT isempty(intervallo_operativo) AND lower_inc(intervallo_operativo) AND NOT upper_inc(intervallo_operativo) AND NOT lower_inf(intervallo_operativo) AND NOT upper_inf(intervallo_operativo))
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_assegnazione_corsa_attiva ON assegnazioni_conducenti(corsa_id) WHERE corsa_id IS NOT NULL AND stato='assegnata';
CREATE UNIQUE INDEX IF NOT EXISTS uq_assegnazione_attivazione_attiva ON assegnazioni_conducenti(attivazione_id) WHERE attivazione_id IS NOT NULL AND stato='assegnata';
ALTER TABLE assegnazioni_conducenti ADD CONSTRAINT assegnazioni_conducenti_no_overlap EXCLUDE USING gist (conducente_id WITH =, intervallo_operativo WITH &&) WHERE (stato='assegnata');

COMMIT;
