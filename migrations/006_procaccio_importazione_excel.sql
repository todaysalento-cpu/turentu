-- Additiva, senza modifiche a PIXEL / POPBUS V2.
-- Eseguire solo dopo backup e verifica.

BEGIN;

-- Numero di contatti pregressi dichiarato nel file Excel.
ALTER TABLE public.procaccio_operatori
  ADD COLUMN IF NOT EXISTS contatti_pregressi INTEGER;

ALTER TABLE public.procaccio_operatori
  DROP CONSTRAINT IF EXISTS procaccio_operatori_contatti_pregressi_ck;

ALTER TABLE public.procaccio_operatori
  ADD CONSTRAINT procaccio_operatori_contatti_pregressi_ck
  CHECK (contatti_pregressi IS NULL OR contatti_pregressi >= 0);

-- Valutazione dell'esito del contatto, non dell'interesse NCC.
ALTER TABLE public.procaccio_attivita
  ADD COLUMN IF NOT EXISTS valutazione_esito SMALLINT;

ALTER TABLE public.procaccio_attivita
  DROP CONSTRAINT IF EXISTS procaccio_attivita_valutazione_esito_ck;

ALTER TABLE public.procaccio_attivita
  ADD CONSTRAINT procaccio_attivita_valutazione_esito_ck
  CHECK (valutazione_esito BETWEEN 1 AND 10);

-- Registro delle importazioni.
CREATE TABLE IF NOT EXISTS public.procaccio_importazioni (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome_file TEXT NOT NULL,
  sha256_file TEXT NOT NULL,
  stato TEXT NOT NULL DEFAULT 'in_corso',
  totale_righe INTEGER NOT NULL DEFAULT 0,
  righe_importate INTEGER NOT NULL DEFAULT 0,
  creato_il TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  completato_il TIMESTAMPTZ,
  dettagli JSONB,
  CONSTRAINT procaccio_importazioni_sha_ck
    CHECK (sha256_file ~ '^[0-9a-f]{64}$'),
  CONSTRAINT procaccio_importazioni_stato_ck
    CHECK (stato IN ('in_corso', 'completata', 'fallita')),
  CONSTRAINT procaccio_importazioni_contatori_ck
    CHECK (
      totale_righe >= 0 AND
      righe_importate >= 0 AND
      righe_importate <= totale_righe
    ),
  CONSTRAINT procaccio_importazioni_sha_unico
    UNIQUE (sha256_file)
);

-- Registro delle righe originali importate.
CREATE TABLE IF NOT EXISTS public.procaccio_importazione_righe (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  importazione_id BIGINT NOT NULL REFERENCES
    public.procaccio_importazioni(id) ON DELETE RESTRICT,
  numero_riga INTEGER NOT NULL,
  operatore_id BIGINT REFERENCES
    public.procaccio_operatori(id) ON DELETE SET NULL,
  attivita_id BIGINT REFERENCES
    public.procaccio_attivita(id) ON DELETE SET NULL,
  dati_originali JSONB NOT NULL,
  stato TEXT NOT NULL DEFAULT 'da_verificare',
  note TEXT,
  creato_il TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT procaccio_importazione_righe_numero_ck
    CHECK (numero_riga >= 2),
  CONSTRAINT procaccio_importazione_righe_stato_ck
    CHECK (stato IN (
      'da_verificare',
      'importata',
      'collegata',
      'saltata',
      'errore'
    )),
  CONSTRAINT procaccio_importazione_righe_unica
    UNIQUE (importazione_id, numero_riga)
);

CREATE INDEX IF NOT EXISTS
  procaccio_importazione_righe_operatore_idx
  ON public.procaccio_importazione_righe (operatore_id);

COMMIT;
