-- TURENTU - Migrazione additiva anagrafica conducenti
-- Eseguire prima in ambiente di staging e dopo backup.
-- Non modifica le tabelle utente, conducenti_operatori o le assegnazioni.
BEGIN;

CREATE TABLE IF NOT EXISTS public.anagrafica_conducenti (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  operatore_id INTEGER NOT NULL REFERENCES public.utente(id),
  nome TEXT NOT NULL,
  cognome TEXT NOT NULL,
  data_nascita DATE,
  email TEXT,
  telefono TEXT,
  categoria_patente TEXT,
  scadenza_patente DATE,
  numero_patente TEXT,
  utente_id INTEGER REFERENCES public.utente(id),
  stato TEXT NOT NULL DEFAULT 'bozza',
  creato_il TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  aggiornato_il TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT anagrafica_conducenti_nome_non_vuoto CHECK (length(btrim(nome)) > 0),
  CONSTRAINT anagrafica_conducenti_cognome_non_vuoto CHECK (length(btrim(cognome)) > 0),
  CONSTRAINT anagrafica_conducenti_stato_check CHECK (stato IN ('bozza','invitato','collegato','disattivato')),
  CONSTRAINT anagrafica_conducenti_collegato_account_check CHECK (stato <> 'collegato' OR utente_id IS NOT NULL)
);

-- Evita che lo stesso account Turentu sia collegato a piu anagrafiche,
-- anche presso operatori diversi. Le righe senza account non sono coinvolte.
CREATE UNIQUE INDEX IF NOT EXISTS anagrafica_conducenti_utente_id_unique
  ON public.anagrafica_conducenti (utente_id)
  WHERE utente_id IS NOT NULL;

-- Impedisce duplicati email nello stesso operatore, senza rendere globale
-- l'unicita dell'email di una bozza non ancora verificata.
CREATE UNIQUE INDEX IF NOT EXISTS anagrafica_conducenti_operatore_email_unique
  ON public.anagrafica_conducenti (operatore_id, lower(btrim(email)))
  WHERE email IS NOT NULL AND btrim(email) <> '' AND stato <> 'disattivato';

CREATE INDEX IF NOT EXISTS anagrafica_conducenti_operatore_idx
  ON public.anagrafica_conducenti (operatore_id, stato);

COMMIT;
