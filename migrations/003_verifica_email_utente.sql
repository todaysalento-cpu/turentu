BEGIN;

ALTER TABLE public.utente
  ADD COLUMN IF NOT EXISTS email_verificata_il TIMESTAMPTZ;

CREATE TABLE IF NOT EXISTS public.verifiche_email_utente (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  utente_id INTEGER NOT NULL REFERENCES public.utente(id) ON DELETE CASCADE,
  email_destinatario TEXT NOT NULL,
  token_hash CHAR(64) NOT NULL UNIQUE,
  scade_il TIMESTAMPTZ NOT NULL,
  consumato_il TIMESTAMPTZ,
  revocato_il TIMESTAMPTZ,
  creato_il TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT verifiche_email_destinatario_non_vuoto CHECK (length(btrim(email_destinatario)) > 0),
  CONSTRAINT verifiche_email_scadenza_valida CHECK (scade_il > creato_il)
);

CREATE INDEX IF NOT EXISTS verifiche_email_utente_lookup_idx
  ON public.verifiche_email_utente (utente_id, creato_il DESC);

CREATE UNIQUE INDEX IF NOT EXISTS verifiche_email_utente_unico_pendente_idx
  ON public.verifiche_email_utente (utente_id)
  WHERE consumato_il IS NULL AND revocato_il IS NULL;

COMMIT;
